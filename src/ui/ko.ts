export function isTechnical(text: string): boolean {
  return text.split(/[\s+×:·,()/%.!?★♛−–—]+/).every((w) => !w || KEEP.has(w) || /^\d+[KMBT]?$/.test(w) || /^[^A-Za-z]+$/.test(w));
}
