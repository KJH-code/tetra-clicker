// Named builds the OPENER bot can play, each opened by one step of the
// OPENER prestige chain. Each stage is a board picture, rows top to bottom
// joined by '/', bottom row on the floor: a piece letter is a cell that
// piece fills, X a cell already filled (an earlier bag's leftovers), _
// empty. The pictures come from pensil.wiki (see THIRD_PARTY.md), read by
// script: every board on a build's page, its spin placements in capitals
// like the rest. The bot plays the first stage its board fits and falls
// back to its DPC search whenever the queue does not fit the build.
// In the order the chain sells them: the least Lines a piece first
// (measured, tests/slow/tech-openers.test.ts).
export interface OpenerDef {
  id: string;
  name: string;
  source: string;
  stages: string[];
}

